// media-work/<campaign>/README.md — regenerated after every render: what exists,
// what to review next, and the spend so far. The spend log (.state/spend.json)
// gets the engine's own paid calls automatically; generations made through MCP
// tools are appended with the `spend` command.

import fs from 'node:fs/promises';
import path from 'node:path';
import { WORK } from './constants.mjs';

const SPEND_FILE = 'spend.json';

export async function readSpend(paths) {
  try {
    return JSON.parse(await fs.readFile(path.join(paths.stateDir, SPEND_FILE), 'utf8'));
  } catch (err) {
    if (err.code === 'ENOENT') return [];
    throw err;
  }
}

/** Append spend entries `{ item, usd, via }` (dated). */
export async function appendSpend(paths, entries) {
  if (!entries.length) return;
  const log = await readSpend(paths);
  const date = new Date().toISOString().slice(0, 10);
  log.push(...entries.map((e) => ({ date, ...e })));
  await fs.mkdir(paths.stateDir, { recursive: true });
  await fs.writeFile(path.join(paths.stateDir, SPEND_FILE), `${JSON.stringify(log, null, 2)}\n`);
}

const mark = (ok) => (ok ? 'yes' : '—');

/** README text. Pure. */
export function campaignReadme({ spec, rows, voiceRows, music, lastRender, spend }) {
  const total = spend.reduce((acc, e) => acc + (Number(e.usd) || 0), 0);
  const missing = rows.filter((r) => !r.clip || !r.still).map((r) => r.id);
  const next = lastRender
    ? `Open \`${WORK.REVIEW}/${spec.locale}/\` (rebuild it with \`cli.mjs review\`) and give feedback per numbered folder.`
    : `Generate the missing inputs${missing.length ? ` (${missing.join(', ')})` : ''}, then render with \`cli.mjs run … --inputs\`.`;
  return [
    `# ${spec.title ?? spec.id}`,
    '',
    `Campaign \`${spec.campaign ?? spec.id}\` · locale \`${spec.locale}\` · generated by the engine after each render — edits are overwritten.`,
    '',
    '## Next',
    '',
    next,
    '',
    '## Inputs',
    '',
    '| Shot | still | clip | result | perfect | line | quip |',
    '|---|---|---|---|---|---|---|',
    ...rows.map((r) => `| ${r.id} | ${mark(r.still)} | ${mark(r.clip)} | ${mark(r.result)} | ${mark(r.perfect)} | ${mark(r.line)} | ${mark(r.quip)} |`),
    '',
    ...voiceRows.map((v) => `- ${v.label}: ${mark(v.ok)}`),
    `- music bed (${WORK.MUSIC}/): ${mark(music)}`,
    '',
    '## Last render',
    '',
    lastRender ? `\`${path.basename(lastRender.file)}\` — ${lastRender.totalSec.toFixed(2)} s, in \`${WORK.RENDERS}/${spec.locale}/\`` : 'None yet.',
    '',
    '## Spend',
    '',
    spend.length ? `Total so far: **$${total.toFixed(2)}** (estimates).` : 'Nothing recorded yet.',
    '',
    ...spend.slice(-15).map((e) => `- ${e.date} · ${e.item} · $${Number(e.usd).toFixed(3)}${e.via ? ` · ${e.via}` : ''}`),
    '',
  ].join('\n');
}

/** Regenerate the campaign README (and log this run's paid engine calls). */
export async function writeCampaignReadme({ spec, paths, inputFiles, lastRender = null, ledger = null }) {
  if (ledger?.items) await appendSpend(paths, ledger.items.filter((e) => e.paid && e.usd > 0).map((e) => ({ item: e.label, usd: e.usd, via: 'engine' })));
  const at = inputFiles;
  const actionPresent = (s) => Boolean(s.action?.length) && s.action.every((p) => at.clipFile(p.file));
  const rows = spec.shots.map((s) => ({
    id: s.id,
    still: Boolean(at.still(s.id)),
    clip: Boolean(at.clip(s.id)) || actionPresent(s),
    result: Boolean(at.resultStill(s.id)),
    perfect: Boolean(at.perfectPhoto(s.id)),
    line: Boolean(at.vo(s.id, 'line')),
    quip: Boolean(at.vo(s.id, 'quip')),
  }));
  const voiceRows = [
    { label: `hook voice (${WORK.VOICE}/${spec.locale}/hook.mp3)`, ok: Boolean(at.vo('hook')) },
    { label: `end-card voice (${WORK.VOICE}/${spec.locale}/endcard.announcer.mp3)`, ok: Boolean(at.vo('endcard', 'announcer')) },
  ];
  const text = campaignReadme({ spec, rows, voiceRows, music: Boolean(at.music()), lastRender, spend: await readSpend(paths) });
  await fs.mkdir(paths.campaignDir, { recursive: true });
  await fs.writeFile(paths.readme, text);
}
