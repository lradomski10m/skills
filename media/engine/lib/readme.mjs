// media-work/<campaign>/README.md — regenerated after every render: the shots and the
// inputs each one used (or a stand-in), the last render, what to review next and the
// spend so far. The spend log (.state/spend.json) is appended by the `spend` command
// for generations made through MCP tools.

import fs from 'node:fs/promises';
import path from 'node:path';
import { WORK } from './constants.mjs';

const SPEND_FILE = 'spend.json';

export async function readSpend(paths) {
  try {
    return JSON.parse(await fs.readFile(path.join(paths.stateDir, SPEND_FILE), 'utf8'));
  } catch (err) {
    if (err.code === 'ENOENT') return [];
    throw err;
  }
}

/** Append spend entries `{ item, usd, via }` (dated). */
export async function appendSpend(paths, entries) {
  if (!entries.length) return;
  const log = await readSpend(paths);
  const date = new Date().toISOString().slice(0, 10);
  log.push(...entries.map((e) => ({ date, ...e })));
  await fs.mkdir(paths.stateDir, { recursive: true });
  await fs.writeFile(path.join(paths.stateDir, SPEND_FILE), `${JSON.stringify(log, null, 2)}\n`);
}

/** README text. Pure. */
export function campaignReadme({ title, campaign, locale, shots, lastRender, spend }) {
  const total = spend.reduce((acc, e) => acc + (Number(e.usd) || 0), 0);
  const standIns = shots.flatMap((s) => Object.entries(s.assets).filter(([, a]) => a.standIn).map(([k]) => `${s.id}.${k}`));
  const next = standIns.length
    ? `Generate the inputs still using stand-ins (${standIns.join(', ')}), ingest them, then render again.`
    : lastRender
      ? `Open \`${WORK.REVIEW}/${locale}/\` (rebuild it with \`cli.mjs review\`) and give feedback per numbered folder.`
      : 'Render with `cli.mjs run`.';
  const cell = (a) => (!a ? '' : a.standIn ? 'stand-in' : path.basename(a.file));
  return [
    `# ${title ?? campaign}`,
    '',
    `Campaign \`${campaign}\` · locale \`${locale}\` · generated by the engine after each render — edits are overwritten.`,
    '',
    '## Next',
    '',
    next,
    '',
    '## Shots',
    '',
    '| Shot | Preset | Start | Inputs |',
    '|---|---|---|---|',
    ...shots.map((s) => `| ${s.id} | ${s.preset} | ${s.startSec.toFixed(2)} s | ${Object.entries(s.assets).map(([k, a]) => `${k}: ${cell(a)}`).join(' · ')} |`),
    '',
    '## Last render',
    '',
    lastRender ? `\`${path.basename(lastRender.file)}\` — ${lastRender.totalSec.toFixed(2)} s, in \`${WORK.RENDERS}/${locale}/\`` : 'None yet.',
    '',
    '## Spend',
    '',
    spend.length ? `Total so far: **$${total.toFixed(2)}** (estimates).` : 'Nothing recorded yet.',
    '',
    ...spend.slice(-15).map((e) => `- ${e.date} · ${e.item} · $${Number(e.usd).toFixed(3)}${e.via ? ` · ${e.via}` : ''}`),
    '',
  ].join('\n');
}

/** Regenerate the campaign README. */
export async function writeCampaignReadme({ sb, paths, tl, lastRender = null }) {
  const text = campaignReadme({ title: sb.front.title, campaign: sb.front.campaign, locale: sb.locale, shots: tl.shots ?? [], lastRender, spend: await readSpend(paths) });
  await fs.mkdir(paths.campaignDir, { recursive: true });
  await fs.writeFile(paths.readme, text);
}
